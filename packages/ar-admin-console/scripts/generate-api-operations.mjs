#!/usr/bin/env node
/**
 * Writes src/lib/settings/api-operations.ts: every operation of the Admin API specs (method,
 * path, summary), for the settings map's API inventory (api-inventory.ts). Run it after an
 * Admin API spec changes; placement.test.ts then shows operations that have no group yet.
 *
 *   node scripts/generate-api-operations.mjs
 */
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { parse } from 'yaml';

const here = path.dirname(fileURLToPath(import.meta.url));
const packages = path.resolve(here, '../..');
const SPECS = [
	{ spec: 'admin', file: 'ar-management/openapi/admin.openapi.yaml', only: null },
	// The SAML service's own Admin API (providers, metadata, local signing).
	{ spec: 'saml', file: 'ar-saml/openapi/saml.openapi.yaml', only: '/api/admin/' }
];
const METHODS = ['get', 'post', 'put', 'patch', 'delete'];

const operations = [];
for (const { spec, file, only } of SPECS) {
	const document = parse(await readFile(path.join(packages, file), 'utf8'));
	for (const [route, item] of Object.entries(document.paths ?? {})) {
		if (only && !route.startsWith(only)) continue;
		for (const method of METHODS) {
			const operation = item[method];
			if (!operation) continue;
			operations.push({
				method: method.toUpperCase(),
				path: route,
				summary: String(operation.summary ?? '').trim(),
				spec
			});
		}
	}
}
operations.sort((a, b) =>
	a.path === b.path
		? METHODS.indexOf(a.method.toLowerCase()) - METHODS.indexOf(b.method.toLowerCase())
		: a.path < b.path
			? -1
			: 1
);

const out = `/**
 * Every operation of the Admin API specs, for the settings map's API inventory. Generated by
 * scripts/generate-api-operations.mjs from ${SPECS.map((s) => s.file).join(' and ')};
 * do not edit by hand.
 */

export type ApiMethod = 'GET' | 'POST' | 'PUT' | 'PATCH' | 'DELETE';

export interface ApiOperation {
	method: ApiMethod;
	path: string;
	summary: string;
	spec: ${SPECS.map((s) => `'${s.spec}'`).join(' | ')};
}

/** [method, path, summary, spec], one operation per line. */
const ROWS: readonly (readonly [ApiMethod, string, string, ApiOperation['spec']])[] = [
${operations.map((o) => `\t${JSON.stringify([o.method, o.path, o.summary, o.spec])},`).join('\n')}
];

export const API_OPERATIONS: readonly ApiOperation[] = ROWS.map(([method, path, summary, spec]) => ({
	method,
	path,
	summary,
	spec
}));
`;
await writeFile(path.join(here, '../src/lib/settings/api-operations.ts'), out);
console.log(`api-operations.ts: ${operations.length} operations`);
