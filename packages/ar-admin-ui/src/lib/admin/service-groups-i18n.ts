export function groupFieldLabel(field: string, text: GroupText): string {
	const builtins = [
		'email',
		'email_domain',
		'email_verified',
		'country',
		'registration_state'
	] as const;
	const builtin = builtins.find((key) => key === field);
	return builtin ? text[builtin] : field;
}
