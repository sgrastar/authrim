/**
 * Builds the waiting scene (city/entry.js with three.js inside it) into one file under
 * public/assets/city/, named by its content, and writes the name into src/city-assets.ts.
 * The output is committed: the Worker is deployed with `wrangler deploy` alone, which builds nothing.
 *
 *   pnpm exec tsx scripts/build-city.ts
 */
import { createHash } from 'node:crypto';
import { mkdirSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { build } from 'esbuild';

const root = resolve(import.meta.dirname, '..');
const outDir = join(root, 'public', 'assets', 'city');

const result = await build({
  entryPoints: [join(root, 'city', 'entry.js')],
  bundle: true,
  minify: true,
  format: 'iife',
  target: ['es2020'],
  legalComments: 'none',
  // See city/random.js.
  define: { 'Math.random': 'cityRandom' },
  inject: [join(root, 'city', 'random.js')],
  write: false,
  logLevel: 'warning',
});
// three.js is MIT licensed; its notice travels with the file that contains it.
const banner = '/*! Contains three.js (c) 2010-2026 three.js authors, MIT License. */\n';
const code = Buffer.concat([Buffer.from(banner), result.outputFiles[0].contents]);
const hash = createHash('sha256').update(code).digest('hex').slice(0, 10);
const name = `city.${hash}.js`;

mkdirSync(outDir, { recursive: true });
for (const file of readdirSync(outDir)) {
  if (/^city\.[0-9a-f]{10}\.js$/.test(file)) rmSync(join(outDir, file));
}
writeFileSync(join(outDir, name), code);
writeFileSync(
  join(root, 'src', 'city-assets.ts'),
  `// Generated by scripts/build-city.ts. Do not edit by hand.\n\n/** The scene's script (three.js inside it): content hash in the name, cached for a year. */\nexport const CITY_SCRIPT = '/assets/city/${name}';\n\n/** Its size in bytes as shipped (before the transfer's own compression). */\nexport const CITY_SCRIPT_BYTES = ${code.length};\n`
);
console.log(`${name}  ${(code.length / 1024).toFixed(1)} KiB`);
