/**
 * Copies the finished gate photographs into `public/assets/gate/` with a content hash in the file
 * name (so they can be cached forever) and writes the two generated modules that describe them:
 * `src/gate-assets.ts` (URL manifest) and `src/gate-geometry.ts` (measured geometry).
 *
 *   pnpm exec tsx scripts/sync-gate-assets.ts <folder with the finished files and geometry.json>
 *
 * The photographs are original, generated images. Only the files listed here are shipped.
 */
import { createHash } from 'node:crypto';
import { copyFileSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { basename, extname, join, resolve } from 'node:path';

const SHIPPED = [
  'far-dark-1600.avif',
  'far-dark-1600.webp',
  'far-dark-2400.avif',
  'far-dark-2400.webp',
  'far-lit-1600.avif',
  'far-lit-1600.webp',
  'far-lit-2400.avif',
  'far-lit-2400.webp',
  'near-dark-1200.avif',
  'near-dark-1200.webp',
  'near-dark-2400.avif',
  'near-dark-2400.webp',
  'near-lit-1200.avif',
  'near-lit-1200.webp',
  'near-lit-2400.avif',
  'near-lit-2400.webp',
  'near-leaf-l.webp',
  'near-leaf-r.webp',
  'near-passage.webp',
  'flame-flipbook.webp',
  'seal.webp',
];

const source = resolve(process.argv[2] ?? '');
if (!process.argv[2]) throw new Error('usage: sync-gate-assets.ts <source folder>');
const root = resolve(import.meta.dirname, '..');
const target = join(root, 'public/assets/gate');
mkdirSync(target, { recursive: true });
for (const old of readdirSync(target)) rmSync(join(target, old));

const manifest: Record<string, string> = {};
for (const name of SHIPPED) {
  const bytes = readFileSync(join(source, name));
  const hash = createHash('sha256').update(bytes).digest('hex').slice(0, 10);
  const ext = extname(name);
  const hashed = `${basename(name, ext)}.${hash}${ext}`;
  copyFileSync(join(source, name), join(target, hashed));
  manifest[name] = `/assets/gate/${hashed}`;
}

const placeholder = readFileSync(join(source, 'placeholder.base64.txt'), 'utf8').trim();
const header = '// Generated by scripts/sync-gate-assets.ts. Do not edit by hand.\n';
writeFileSync(
  join(root, 'src/gate-assets.ts'),
  `${header}
/** Logical file name -> served URL (content hash in the name; cached for a year). */
export const GATE_ASSETS: Record<string, string> = ${JSON.stringify(manifest, null, 2)};

/** 24x16 blurred far view, inlined in the stylesheet. */
export const GATE_PLACEHOLDER = ${JSON.stringify(placeholder)};
`
);

interface Fire {
  id: string;
  pair: string;
  side: string;
  center: number[];
  radius: number;
  flameWidth: number;
  flameHeight: number;
}
const geometry = JSON.parse(readFileSync(join(source, 'geometry.json'), 'utf8')) as {
  far: { opening: { bounds: number[] }; nearRect: object; fires: Fire[]; seal: object };
  near: {
    opening: { bounds: number[]; springY: number };
    leaves: object;
    seamX: number;
    vanishingPoint: number[];
    seal: { center: number[]; radius: number };
    fires: Fire[];
  };
  camera: { fixedPoint: number[]; stationScales: number[]; parallaxEnabled: boolean };
};
const round = (n: number) => Math.round(n * 10000) / 10000;
const fire = (f: Fire) => ({
  id: f.id,
  pair: f.pair,
  side: f.side,
  x: round(f.center[0]),
  y: round(f.center[1]),
  radius: round(f.radius),
  flameWidth: round(f.flameWidth),
  flameHeight: round(f.flameHeight),
});
const out = {
  far: {
    nearRect: geometry.far.nearRect,
    fires: geometry.far.fires.map(fire),
  },
  near: {
    opening: geometry.near.opening.bounds.map(round),
    seamX: round(geometry.near.seamX),
    vanishingPoint: geometry.near.vanishingPoint.map(round),
    seal: {
      x: round(geometry.near.seal.center[0]),
      y: round(geometry.near.seal.center[1]),
      radius: round(geometry.near.seal.radius),
    },
    fires: geometry.near.fires.map(fire),
  },
  camera: {
    fixedPoint: geometry.camera.fixedPoint.map(round),
    stationScales: geometry.camera.stationScales.map((n) => round(n)),
  },
  parallaxEnabled: geometry.camera.parallaxEnabled,
};
writeFileSync(
  join(root, 'src/gate-geometry.ts'),
  `${header}
/** Measured on the finished photographs (REPORT: these win over the design targets). Normalised, origin top-left; radii and flame sizes are relative to the image width. */
export const GATE_GEOMETRY = ${JSON.stringify(out, null, 2)} as const;
`
);
console.log(`copied ${SHIPPED.length} files`);
