export function samlDrWriterSurfaces(component: SamlDrWriterComponent): readonly string[] {
  const surfaces = SURFACES[component];
  if (!surfaces?.length) throw new Error('saml_dr_writer_contract_unavailable');
  return surfaces;
}

/** Names backed by guarded code or explicitly excluded protocol/deployment state. */
export function samlDrDurableObjectClasses(component: SamlDrWriterComponent): readonly string[] {
  return [
    ...new Set(
      samlDrWriterSurfaces(component).flatMap((surface) => {
        const match = /:do:([A-Za-z0-9_]+)(?:\.|$)/u.exec(surface);
        if (match) return [match[1]];
        return surface.startsWith('guarded:mcp:AgentAccessMcpAgent.')
          ? ['AgentAccessMcpAgent']
          : [];
      })
    ),
  ].sort();
}

export async function samlDrContractSha256(value: string): Promise<string> {
  const bytes = await crypto.subtle.digest('SHA-256', new TextEncoder().encode(value));
  return Array.from(new Uint8Array(bytes), (byte) => byte.toString(16).padStart(2, '0')).join('');
}

export function samlDrWriterContractDigest(component: SamlDrWriterComponent): Promise<string> {
  return samlDrContractSha256(
    JSON.stringify({
      formatVersion: 1,
      component,
      surfaces: samlDrWriterSurfaces(component),
    })
  );
}
