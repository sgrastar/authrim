export function createSignableResponse(id: string, assertionId = `${id}_assertion`): string {
  return `<?xml version="1.0" encoding="UTF-8"?>
<samlp:Response xmlns:samlp="urn:oasis:names:tc:SAML:2.0:protocol"
  xmlns:saml="urn:oasis:names:tc:SAML:2.0:assertion"
  ID="${id}" Version="2.0" IssueInstant="2026-01-01T00:00:00Z">
  <saml:Issuer>https://idp.example.com</saml:Issuer>
  <saml:Assertion ID="${assertionId}" Version="2.0" IssueInstant="2026-01-01T00:00:00Z">
    <saml:Issuer>https://idp.example.com</saml:Issuer>
  </saml:Assertion>
</samlp:Response>`;
}

export function signReference(xml: string, referenceUri: string): string {
  return signXml(xml, {
    privateKey: TEST_PRIVATE_KEY,
    certificate: TEST_CERTIFICATE,
    referenceUri,
  });
}

/** Sign with xml-crypto directly, optionally covering several elements. */
export function signReferences(
  xml: string,
  id: string,
  references: string[],
  signatureAlgorithm: string = SIGNATURE_ALGORITHMS.RSA_SHA256
): string {
  const sig = new SignedXml({
    privateKey: TEST_PRIVATE_KEY,
    signatureAlgorithm,
    canonicalizationAlgorithm: CANONICALIZATION_ALGORITHMS.EXCLUSIVE_C14N,
  });
  for (const referencedId of references) {
    sig.addReference({
      xpath: `//*[@ID='${referencedId}']`,
      digestAlgorithm: DIGEST_ALGORITHMS.SHA256,
      transforms: [
        'http://www.w3.org/2000/09/xmldsig#enveloped-signature',
        CANONICALIZATION_ALGORITHMS.EXCLUSIVE_C14N,
      ],
    });
  }
  sig.computeSignature(xml, { location: { reference: `//*[@ID='${id}']`, action: 'prepend' } });
  return sig.getSignedXml();
}
